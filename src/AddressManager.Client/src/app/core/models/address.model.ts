/**
 * Интерфейс адреса — соответствует DTO, которое возвращает API (GET /api/addresses).
 *
 * Поля намеренно плоские: вместо вложенных объектов City/Region/Country
 * API возвращает их имена в виде строк — это упрощает отображение в таблице.
 */
export interface Address {
  /** Уникальный идентификатор адреса в базе данных. */
  id: number;

  /** Название улицы, проспекта, переулка и т.д. */
  street: string;

  /** Номер дома (строка — может содержать литеры: "12А"). */
  houseNumber: string;

  /** Номер квартиры. null, если адрес без квартиры (частный дом, офис). */
  apartmentNumber: string | null;

  /** Почтовый индекс (строка — формат зависит от страны: "01001", "00-026"). */
  postalCode: string;

  /** Название города. */
  city: string;

  /** Название региона (область / воеводство / земля). */
  region: string;

  /** Полное название страны. */
  country: string;

  /**
   * Двухбуквенный код страны по ISO 3166-1 alpha-2.
   * Используется для генерации флага-эмодзи на клиенте.
   * Примеры: "UA", "PL", "DE".
   */
  countryCode: string;
}
